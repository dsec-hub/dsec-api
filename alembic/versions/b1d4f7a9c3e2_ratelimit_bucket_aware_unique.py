    op.execute(_DEDUPE_SQL)

    # Drop the old (key_id, window_start) unique constraint.
    op.execute(f"ALTER TABLE rate_limit DROP CONSTRAINT IF EXISTS {_OLD_CONSTRAINT}")

    # NULLS NOT DISTINCT needs PG15+. Fall back to a plain bucket-aware unique
    # index on older servers (still fixes problem 1; problem 2 stays mitigated by
