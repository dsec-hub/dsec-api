"""rate_limit: make the unique key bucket-aware + NULLS NOT DISTINCT

The old unique key was (key_id, window_start), excluding `bucket`. Two problems
that fix cleanly together:

1. A request at exactly 00:00 UTC creates a per-minute row (bucket='req') and a
   per-day trigger row (bucket='trigger') that share window_start=midnight — they
   collided under the old key. Adding `bucket` separates them.
2. Per-IP rows carry key_id=NULL, and Postgres treats NULLs as DISTINCT in a
   unique index, so two concurrent first-of-window per-IP requests could both
   insert and split the counter into duplicate rows. NULLS NOT DISTINCT (PG15+)
   makes them collide, so the limiter's insert/on-conflict path converges.

HAND-WRITTEN (never autogenerated against Neon — see the team rule). Idempotent
and Postgres-only: on any other dialect it is a no-op, because SQLite dev builds
the schema from the models + stamps head and never replays this chain.

Revision ID: b1d4f7a9c3e2
Revises: a2e6c4f8b1d3
Create Date: 2026-08-29
"""
