_OLD_CONSTRAINT = "uq_ratelimit_key_window"
_NEW_INDEX = "uq_ratelimit_key_bucket_window"

# Fold duplicate (key_id, bucket, window_start) rows into the lowest id, summing
# both counters, then delete the extras — so the new unique index can be built.
# GROUP BY / PARTITION BY fold NULL key_ids together, matching NULLS NOT DISTINCT.
_DEDUPE_SQL = """
UPDATE rate_limit r SET
    count = agg.sum_count,
    trigger_count_today = agg.sum_trigger
FROM (
    SELECT MIN(id) AS keep_id,
           SUM(count) AS sum_count,
           SUM(trigger_count_today) AS sum_trigger
    FROM rate_limit
    GROUP BY key_id, bucket, window_start
    HAVING COUNT(*) > 1
) agg
WHERE r.id = agg.keep_id;

DELETE FROM rate_limit r
USING (
    SELECT id,
           MIN(id) OVER (PARTITION BY key_id, bucket, window_start) AS keep_id
    FROM rate_limit
) d
WHERE r.id = d.id AND d.id <> d.keep_id;
"""


def _is_postgres() -> bool:
    return op.get_bind().dialect.name == "postgresql"


